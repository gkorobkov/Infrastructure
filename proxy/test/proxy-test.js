function bind(server){return new Promise(resolve=>server.listen(0,'127.0.0.1',()=>resolve(server.address().port)));}
function close(server){return new Promise(resolve=>server.close(resolve));}
function incomingBody(request){return new Promise((resolve,reject)=>{let chunks=[];request.on('data',data=>chunks.push(data));request.on('end',()=>resolve(Buffer.concat(chunks)));request.on('error',reject);});}

before(async()=>{
  upstream=http.createServer(async(req,res)=>{
    if(req.url==='/events'){
      res.writeHead(200,{'Content-Type':'text/event-stream'});
      res.write('data: first\n\n');
      setTimeout(()=>res.end('data: second\n\n'),65);return;
    }
    if(req.url==='/redirect') {res.writeHead(302,{Location:'/final'});res.end();return;}
    if(req.url==='/final'){res.writeHead(200);res.end('redirected');return;}
    if(req.url==='/fail'){res.writeHead(429,{'Content-Type':'text/plain','Retry-After':'12'});res.end('slow down');return;}
    const body=await incomingBody(req);
    res.writeHead(200,{'Content-Type':'application/json','X-Upstream-Custom':'yes'});
    res.end(JSON.stringify({method:req.method,url:req.url,headers:req.headers,bodyBase64:body.toString('base64')}));
  });
  upstreamPort=await bind(upstream);
  server=createProxyServer({port:0,resolveTarget:async()=> (_host,opts,callback)=>opts?.all ? callback(null,[{address:'127.0.0.1',family:4}]) : callback(null,'127.0.0.1',4)});
  const port=await listen(server,0);proxyUrl=`http://127.0.0.1:${port}`;
  origin=`http://example.test:${upstreamPort}`;
});
after(async()=>{await close(server);await close(upstream);});

function proxyHeaders(url,extra={}){return {Origin:permitted,'X-Proxy-Target-URL':url,...extra};}

test('health and unknown route',async()=>{
  const r=await fetch(proxyUrl+'/health',{headers:{Host:`127.0.0.1:${server.address().port}`}});
  assert.equal(r.status,200);assert.equal((await r.json()).status,'ok');
  const r2=await fetch(proxyUrl+'/missing');assert.equal(r2.status,404);
});
test('preflight includes requested authorization and target header',async()=>{
  const r=await fetch(proxyUrl+'/proxy',{method:'OPTIONS',headers:{Origin:permitted,'Access-Control-Request-Method':'POST','Access-Control-Request-Headers':'authorization, content-type, x-proxy-target-url'}});
  assert.equal(r.status,204);assert.match(r.headers.get('access-control-allow-headers'),/authorization/);
  assert.equal(r.headers.get('access-control-allow-origin'),permitted);
});
test('deny missing or unknown Origin',async()=>{
  for(const headers of [{'X-Proxy-Target-URL':origin},proxyHeaders(origin,{Origin:'https://evil.test'})]){
    const r=await fetch(proxyUrl+'/proxy',{headers});assert.equal(r.status,403);
  }
});
test('request method, repeated query, headers, body bytes and response headers',async()=>{
  const body=Buffer.from([0,255,34,3,128,61]);
  const target=origin+'/echo?a=1&a=2&empty=&x=%2F';
  const r=await fetch(proxyUrl+'/proxy',{method:'POST',headers:proxyHeaders(target,{'Content-Type':'application/octet-stream','Authorization':'Bearer secret','X-Custom':'yes'}),body});
  assert.equal(r.status,200);assert.equal(r.headers.get('x-upstream-custom'),'yes');
  const data=await r.json();assert.equal(data.method,'POST');assert.equal(data.url,'/echo?a=1&a=2&empty=&x=%2F');
  assert.equal(data.headers.authorization,'Bearer secret');assert.equal(data.headers['x-custom'],'yes');assert.equal(data.headers['x-proxy-target-url'],undefined);
  assert.equal(data.headers.origin,undefined);assert.equal(data.bodyBase64,body.toString('base64'));
});
test('multipart passes through unchanged',async()=>{
  const data=new FormData();data.set('file',new Blob([Buffer.from([0,1,2,255])]),'test.bin');data.set('name','русский');
  const expected=await new Response(data).arrayBuffer();
  const r=await fetch(proxyUrl+'/proxy',{method:'POST',headers:proxyHeaders(origin+'/upload'),body:data});
  const received=await r.json();assert.match(received.headers['content-type'],/^multipart\/form-data; boundary=/);
  // Multipart boundary is generated anew by fetch, so verify payload structure, not separately-generated bytes.
  const raw=Buffer.from(received.bodyBase64,'base64');assert.ok(raw.includes(Buffer.from('test.bin')));assert.ok(raw.includes(Buffer.from([0,1,2,255])));
  assert.ok(expected.byteLength>0);
});
test('external HTTP failures are returned unchanged',async()=>{
  const r=await fetch(proxyUrl+'/proxy',{headers:proxyHeaders(origin+'/fail')});
  assert.equal(r.status,429);assert.equal(await r.text(),'slow down');assert.equal(r.headers.get('retry-after'),'12');
});
test('SSE streams first event before end',async()=>{
  const r=await fetch(proxyUrl+'/proxy',{headers:proxyHeaders(origin+'/events')});
  assert.equal(r.headers.get('content-type'),'text/event-stream');
  const reader=r.body.getReader(),decoder=new TextDecoder();
  const first=await reader.read();assert.match(decoder.decode(first.value),/first/);
  const second=await reader.read();assert.match(decoder.decode(second.value),/second/);
});
test('redirect follows safely',async()=>{
  const r=await fetch(proxyUrl+'/proxy',{headers:proxyHeaders(origin+'/redirect')});
  assert.equal(r.status,200);assert.equal(await r.text(),'redirected');
});
test('target URL validation and private IPv4/IPv6 blocked',async()=>{
  // Test forbidden targets with production DNS/address policy (no injected resolver).
  const protectedServer=createProxyServer({port:0});
  const protectedPort=await listen(protectedServer,0);
  try {
    for(const url of ['http://127.0.0.1/','http://192.168.1.2/','http://[::1]/','http://169.254.169.254/']) {
      const r=await fetch('http://127.0.0.1:'+protectedPort+'/proxy',{headers:proxyHeaders(url)});
      assert.equal(r.status,403,'Must reject '+url);
    }
  } finally { await close(protectedServer); }
  for(const address of ['127.0.0.1','192.168.3.3','10.0.0.1','169.254.169.254','::1','fe80::1','fc00::1','::ffff:127.0.0.1'])assert.equal(isPublicIP(address),false,address);
  assert.equal(isPublicIP('1.1.1.1'),true);
  assert.throws(()=>parseTarget('file:///etc/passwd'));
  await assert.rejects(()=>resolvePublicTarget(new URL('http://example.test'),async()=>[{address:'127.0.0.1',family:4}]),{code:'PROXY_TARGET_FORBIDDEN'});
});
